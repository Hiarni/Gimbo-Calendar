fun Context.text(source: String, vararg arguments: Any): String =
    LocalizedText.resources[source]?.let { getString(it, *arguments) } ?: source
fun Context.userError(message: String?): String =
    message?.takeIf { LocalizedText.resources.containsKey(it) }?.let { text(it) }
        ?: text("Bitte Eingaben prüfen.")
class Texts(val context: Context) {
    val locale get() = context.resources.configuration.locales[0]
    operator fun invoke(source: String, vararg arguments: Any) = context.text(source, *arguments)
    fun error(message: String?) = context.userError(message)
}
@Composable fun texts(): Texts {
    LocalConfiguration.current
    return Texts(LocalContext.current)
}
